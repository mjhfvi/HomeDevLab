import pendulum
from airflow import DAG
from airflow.providers.cncf.kubernetes.operators.kubernetes_pod import KubernetesPodOperator
from airflow.providers.cncf.kubernetes.operators.pod_exec import KubernetesPodExecOperator

with DAG(
    dag_id='k8s_pod_exec_hello_world',
    schedule=None,
    start_date=pendulum.datetime(2026, 1, 1, tz='UTC'),
    catchup=False,
    tags=['example', 'k8s'],
) as dag:

    # 1. Create a running pod that stays alive (e.g., sleeping for 10 minutes)
    # This pod acts as the baseline execution target.
    start_base_pod = KubernetesPodOperator(
        task_id='start_base_pod',
        name='exec-target-pod',
        namespace='default',  # Change to your target namespace
        image='alpine:latest',
        cmds=['sh', '-c'],
        arguments=["echo 'Pod started. Going to sleep...'; sleep 600"],
        as_current_user=True,
        get_logs=True,
        # Keep the pod running after this task ends so downstream exec tasks can use it
        is_delete_operator_pod=False,
    )

    # 2. Execute a "Hello World" command inside the container of the pod we just launched
    run_hello_world = KubernetesPodExecOperator(
        task_id='run_hello_world',
        # Dynamically fetch the pod name generated by the upstream task
        pod_name="{{ ti.xcom_pull(task_ids='start_base_pod') }}",
        pod_namespace='default',
        # The command to run inside the existing container
        command=['echo', 'Hello World from KubernetesPodExecOperator!'],
    )

    # 3. Clean up the pod after we're finished with it
    # Note: For production, you may want to use a trigger rule to ensure cleanup even if the exec fails
    cleanup_pod = KubernetesPodOperator(
        task_id='cleanup_pod',
        name='cleanup-target-pod',
        namespace='default',
        image='alpine:latest',
        cmds=['sh', '-c'],
        # Delete the specific pod we spun up initially
        arguments=["kubectl delete pod {{ ti.xcom_pull(task_ids='start_base_pod') }}"],
    )

    start_base_pod >> run_hello_world >> cleanup_pod
